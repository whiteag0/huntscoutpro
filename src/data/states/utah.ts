//
// METHOD
//  - gmu = UDWR management-unit code as printed in the report ('/' -> '-', letters upper-cased),
//    e.g. '16A' (Nebo), '17BC' (Wasatch Mtns, East), '25C-26' (Boulder/Kaiparowits).
//    Unit groupings change between years (e.g. elk '8' North Slope in 2021–23 was split into
//    '8A'/'8B'/'8C' in 2024), so some ids only have rows for some years.
//  - Deer/elk/moose: one published row per unit. totalHarvest = "Total harvest" (all hunts:
//    general season, limited entry, antlerless, CWMU, mitigation), totalHunters = "Hunters afield",
//    successRate = the agency's published "Success rate (%)" (computed by UDWR from raw survey data).
//    elk/moose `bulls` = "Bull harvest".
//  - Pronghorn/sheep/goat: subunit / hunt rows summed to the unit code; when more than one row was
//    summed, successRate = harvest / hunters * 100 (1 decimal), otherwise the published rate.
//    Sheep = desert bighorn + Rocky Mountain bighorn (their unit codes do not overlap); includes
//    conservation-permit hunts that are tied to one unit. Statewide sportsman permits are excluded.
//  - Bear & lion: UDWR does not publish hunters afield by unit -> totalHunters 0, successRate 0
//    (unknown). totalHarvest = hunter harvest (male + female + unknown), excluding depredation.
//  - 2025 season: only bear and cougar annual reports exist for 2025. The 2025 Big Game Annual
//    Report and 2025 LE/OIAL/antlerless harvest reports were not yet published (only a preliminary
//    2025 general-season buck deer report exists, not used because it is partial/preliminary).

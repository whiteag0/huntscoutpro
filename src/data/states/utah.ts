//  [BCF] 2026 Utah Bear, Cougar and Furbearer Guidebook: https://wildlife.utah.gov/guidebooks/black-bear-cougar-furbearer-guidebook.pdf
//  [ANT] 2026 Utah Antlerless Application Guidebook: https://wildlife.utah.gov/guidebooks/antlerless_guidebook.pdf
//  Unit relabels (fact-check 2026-10-08): the agency renamed some unchanged hunts between report years; ids are
//  normalized to the current code so one place = one unit id (continuity shown in each report's 10-year trend table):
//  pronghorn '21' (2021–22) -> '21A' Fillmore, Oak Creek South; pronghorn '25' (2021) -> '25C' Parker Mtn;
//  sheep/goat '16' (2021–22) -> '16A' Nebo (same hunts RS6719/RS6725, GO6803, GO6821); pronghorn 2022 unit '9'

#!/usr/bin/env node
// Regenerates src/data/agency/index.generated.ts (state meta + which species files
// exist), live.generated.ts, stats.generated.json and the gzipped tables in
// .agency-gz/ that the API reads. Runs automatically before `npm run build`.
// Run from the repo root after adding or removing data files:
//   node scripts/agency/build-index.mjs
import fs from "node:fs";
import path from "node:path";
import zlib from "node:zlib";

const base = path.join(process.cwd(), "src/data/agency");
const states = fs
  .readdirSync(base, { withFileTypes: true })
  .filter((d) => d.isDirectory() && fs.existsSync(path.join(base, d.name, "draw-meta.json")))
  .map((d) => d.name)
  .sort();

const q = JSON.stringify;
const lines = [
  "// GENERATED by scripts/agency/build-index.mjs — do not edit by hand.",
  'import "server-only";',
  "",
];
const entries = [];
states.forEach((s, i) => {
  const list = (sub) =>
    fs.existsSync(path.join(base, s, sub))
      ? fs.readdirSync(path.join(base, s, sub)).filter((f) => f.endsWith(".json")).map((f) => f.replace(/\.json$/, "")).sort()
      : [];
  const hm = fs.existsSync(path.join(base, s, "harvest-meta.json"));
  lines.push(`import drawMeta${i} from ${q(`./${s}/draw-meta.json`)};`);
  if (hm) lines.push(`import harvestMeta${i} from ${q(`./${s}/harvest-meta.json`)};`);
  entries.push(`  ${q(s)}: { drawMeta: drawMeta${i}, harvestMeta: ${hm ? `harvestMeta${i}` : "null"}, draw: ${q(list("draw"))}, harvest: ${q(list("harvest"))} },`);
});
lines.push(
  "",
  "export interface StateFiles {",
  "  drawMeta: unknown;",
  "  harvestMeta: unknown | null;",
  "  /** Species with a draw/<species>.json file (read from disk on demand). */",
  "  draw: string[];",
  "  /** Species with a harvest/<species>.json file. */",
  "  harvest: string[];",
  "}",
  "",
  "export const AGENCY_FILES: Record<string, StateFiles> = {",
  ...entries,
  "};",
  ""
);
fs.writeFileSync(path.join(base, "index.generated.ts"), lines.join("\n"));
// Client-safe list of states that have data (drives "live" vs "coming soon").
fs.writeFileSync(
  path.join(base, "live.generated.ts"),
  `// GENERATED by scripts/agency/build-index.mjs — do not edit by hand.\nexport const LIVE_SLUGS: readonly string[] = ${JSON.stringify(states)};\n`
);
// Small precomputed summaries so pages never need the big tables at runtime.
const readRows = (s, kind, sp) => {
  const f = path.join(base, s, kind, `${sp}.json`);
  return fs.existsSync(f) ? JSON.parse(fs.readFileSync(f, "utf8")) : [];
};
const stats = { states: states.length, species: {}, drawYears: null, harvestYears: null, turkeyStatewide: {}, completeness: {} };

// What the agency publishes in a species' latest draw with odds: hunt counts only, nothing estimated.
// Mirrors oddsYear() and firstChoiceRows() in src/lib/agency-view.ts (keep them in step).
const hasOdds = (s) => !!s && (s.oddsPct != null || (!!s.applicants && s.drawn != null));
const pools = (r) => [r.resident, r.nonresident, r.total];
const oddsData = (r) => (r.byPoints?.length ?? 0) > 0 || pools(r).some((s) => hasOdds(s) || (!!s && s.minPoints != null));
function drawCompleteness(draw, pointsMatter) {
  if (!draw.length) return null;
  const latest = draw.reduce((m, r) => Math.max(m, r.year), 0);
  const year = draw.filter(oddsData).reduce((m, r) => Math.max(m, r.year), 0) || null;
  // Hunts in that year, or in the latest year when no year has odds (they count as hunts without odds).
  const byCode = new Map();
  for (const r of draw) {
    if (r.year !== (year ?? latest)) continue;
    const cur = byCode.get(r.huntCode);
    if (!cur || (cur.choice !== "first" && r.choice === "first")) byCode.set(r.huntCode, r);
  }
  const rows = [...byCode.values()];
  const count = (f) => rows.filter(f).length;
  return {
    pointsMatter: !!pointsMatter,
    drawYear: year,
    newer: year !== null && latest > year ? latest : null,
    hunts: rows.length,
    odds: count((r) => pools(r).some(hasOdds)),
    // Odds for residents or nonresidents on their own: the pool's figures, or a point table (always split by residency).
    split: count((r) => hasOdds(r.resident) || hasOdds(r.nonresident) || (r.byPoints?.length ?? 0) > 0),
    pointTable: count((r) => (r.byPoints?.length ?? 0) > 0),
    minPoints: count((r) => pools(r).some((s) => !!s && s.minPoints != null) || (r.byPoints?.length ?? 0) > 0),
  };
}
const span = (cur, ys) => ys.reduce((m, y) => (m ? [Math.min(m[0], y), Math.max(m[1], y)] : [y, y]), cur);
for (const s of states) {
  const meta = JSON.parse(fs.readFileSync(path.join(base, s, "draw-meta.json"), "utf8"));
  for (const info of meta.species || []) {
    const sp = info.species;
    const draw = readRows(s, "draw", sp);
    const harvest = readRows(s, "harvest", sp);
    if (info.drawSystem === "none" || (!draw.length && !harvest.length)) continue;
    const latest = draw.reduce((m, r) => Math.max(m, r.year), 0);
    const cur = stats.species[sp] || { states: 0, huntCodes: 0, units: 0 };
    cur.states += 1;
    cur.huntCodes += new Set(draw.filter((r) => r.year === latest).map((r) => r.huntCode)).size;
    cur.units += new Set(harvest.filter((r) => r.unit !== "Statewide").map((r) => r.unit)).size;
    stats.species[sp] = cur;
    const dc = drawCompleteness(draw, info.pointsMatter);
    if (dc) (stats.completeness[s] ||= {})[sp] = dc;
    stats.drawYears = span(stats.drawYears, draw.map((r) => r.year));
    stats.harvestYears = span(stats.harvestYears, harvest.map((r) => r.year));
    if (sp === "turkey") {
      const whole = harvest.filter((r) => r.unit === "Statewide" && !r.hunt && (!r.sex || r.sex === "all") && (!r.residency || r.residency === "all"));
      const byYear = new Map();
      for (const r of whole) {
        const c = byYear.get(r.year);
        if (!c || (r.method === "all" && c.method !== "all")) byYear.set(r.year, r);
      }
      stats.turkeyStatewide[s] = {
        rows: [...byYear.values()].sort((a, b) => b.year - a.year),
        units: new Set(harvest.filter((r) => r.unit !== "Statewide").map((r) => r.unit)).size,
        drawHunts: new Set(draw.map((r) => r.huntCode)).size,
      };
    }
  }
}
fs.writeFileSync(path.join(base, "stats.generated.json"), JSON.stringify(stats, null, 1) + "\n");

// Gzipped copies of the species tables for the API route (gitignored, rebuilt on every build).
const gzRoot = path.join(process.cwd(), ".agency-gz");
fs.rmSync(gzRoot, { recursive: true, force: true });
let gzBytes = 0;
for (const s of states) {
  for (const kind of ["draw", "harvest"]) {
    const dir = path.join(base, s, kind);
    if (!fs.existsSync(dir)) continue;
    fs.mkdirSync(path.join(gzRoot, s, kind), { recursive: true });
    for (const f of fs.readdirSync(dir).filter((f) => f.endsWith(".json"))) {
      const rows = JSON.parse(fs.readFileSync(path.join(dir, f), "utf8"));
      const gz = zlib.gzipSync(JSON.stringify(rows), { level: 9 });
      gzBytes += gz.length;
      fs.writeFileSync(path.join(gzRoot, s, kind, `${f}.gz`), gz);
    }
  }
}
console.log(`.agency-gz: ${(gzBytes / 1e6).toFixed(1)} MB`);

console.log(`index.generated.ts: ${states.length} states (${states.join(", ")})`);
